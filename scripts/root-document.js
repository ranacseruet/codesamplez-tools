// @ts-check

const { buildAbsoluteUrl } = require('./tool-manifest');
const { escapeAttribute, escapeHtml, formatRootDocumentTitle } = require('./document-helpers');
const { getGroupedToolDefinitions, loadManifest } = require('./tool-manifest');
const { renderRootPageIntro, renderRootPagePostIndexSections } = require('./root-page-content');
const { buildRootStructuredDataGraph, renderStructuredDataScript } = require('./structured-data');
const { renderAnalyticsHeadMarkup, renderAnalyticsResourceHints } = require('./analytics');
const { renderInlineIcon } = require('./lucide-icons');
const { getGroupCategorySlug } = require('./tool-categories');

const THEME_COLOR = '#0b0b11';

// Social card dimensions — matches the 1200x630 OG images generated by
// scripts/generate-og-images.mjs.
const OG_IMAGE_WIDTH = '1200';
const OG_IMAGE_HEIGHT = '630';

// Pre-paint theme init: apply the saved theme (default dark) before CSS paints
// so the choice persists across pages with no flash. Must run before stylesheets.
const THEME_INIT_SCRIPT = `<script>(function(){try{var t=localStorage.getItem('cst-standalone-theme-mode');var m=t==='light'?'light':'dark';var e=document.documentElement;e.setAttribute('data-theme',m);e.setAttribute('data-cst-theme',m);}catch(e){}})();</script>`;

// v2 design system: self-hosted Geist fonts (icons are inlined SVGs — no CDN).
// Preloads use the configured static-root absolute URL so they resolve to the
// same asset origin as the stylesheets (pages and assets can be cross-origin).
// The landing page renders no code, so only the body/UI font (Geist) is on the
// first-paint path — GeistMono (~71 KB woff2) is intentionally NOT preloaded here
// and is still fetched on demand via @font-face (font-display: swap) if any
// monospace text appears. Tool pages, which mount code editors above the fold,
// preload both (see tool-document.js).
function renderFontPreloads(staticRootUri) {
    return ['Geist-Variable.woff2']
        .map((file) => `<link rel="preload" href="${escapeAttribute(buildAbsoluteUrl(staticRootUri, `/fonts/${file}`))}" as="font" type="font/woff2" crossorigin>`)
        .join('\n  ');
}

// Favicons resolve against the configured static-root absolute URL (same origin
// as the stylesheets/fonts). SVG is the primary icon; ICO/PNG are fallbacks.
function renderFaviconLinks(staticRootUri) {
    return [
        `<link rel="icon" href="${escapeAttribute(buildAbsoluteUrl(staticRootUri, '/favicon.ico'))}" sizes="any">`,
        `<link rel="icon" type="image/svg+xml" href="${escapeAttribute(buildAbsoluteUrl(staticRootUri, '/favicon.svg'))}">`,
        `<link rel="apple-touch-icon" href="${escapeAttribute(buildAbsoluteUrl(staticRootUri, '/apple-touch-icon.png'))}">`
    ].join('\n  ');
}

/**
 * @typedef {import('./tool-manifest').ToolDefinition} ToolDefinition
 */

/**
 * v4 card: the whole card is clickable via the stretched title link (one tab
 * stop); the "Try Tool" button is a visual affordance only. The status badge
 * renders only for non-live tools — a "Live" pill on every card is noise.
 * @param {ToolDefinition} tool
 * @param {string} categorySlug
 * @returns {string}
 */
function renderToolCard(tool, categorySlug) {
    const iconName = tool.icon || 'wrench';
    const statusBadge = tool.status === 'soon'
        ? '\n          <span class="tool-status tool-status--soon">Soon</span>'
        : '';
    return `      <article class="tool-card tool-card--${escapeAttribute(categorySlug)}" data-tool-id="${escapeAttribute(tool.id)}">
        <div class="tool-card__head">
          <span class="tool-icon-tile" aria-hidden="true">${renderInlineIcon(iconName)}</span>${statusBadge}
        </div>
        <div class="tool-content">
          <h3 class="tool-name"><a class="tool-card__link" href="${escapeAttribute(tool.absolutePageUrl)}">${escapeHtml(tool.title)}</a></h3>
          <p class="tool-description">${escapeHtml(tool.indexDescription)}</p>
          <span class="cta-button cta-button--card" aria-hidden="true">Try Tool${renderInlineIcon('arrow-right')}</span>
        </div>
      </article>`;
}

/**
 * SSR'd search shell (input + category chip anchors). The root-shell bundle
 * re-renders this with behavior (palette, filtering, shortcuts); without JS
 * the chips still work as section anchors and the grid stays fully visible.
 * @param {Array<{ id: string, label: string }>} catalogGroups
 * @returns {string}
 */
function renderToolSearchShell(catalogGroups) {
    const chips = catalogGroups.map((group) => {
        const slug = getGroupCategorySlug(group.id);
        return `      <a class="tool-search__chip tool-search__chip--${escapeAttribute(slug)}" role="button" href="#group-${escapeAttribute(group.id)}">${escapeHtml(group.label)}</a>`;
    }).join('\n');
    return `    <div class="tool-search" id="tool-search-root">
      <div class="tool-search__box">
        ${renderInlineIcon('search', 'tool-search__icon')}
        <input class="tool-search__input" type="search" placeholder="Search tools…" aria-label="Search tools" autocomplete="off" spellcheck="false">
        <kbd class="tool-search__kbd" aria-hidden="true">⌘K</kbd>
      </div>
      <div class="tool-search__chips">
      <a class="tool-search__chip tool-search__chip--all" role="button" href="#tools">All tools</a>
${chips}
      </div>
    </div>`;
}

/**
 * Empty slot for the client-rendered "Recently used" row (Phase D3). The list
 * is per-visitor, so nothing can be server-rendered here; the slot collapses
 * (`:empty` in styles.css) until root-shell fills it, so first-time visitors
 * see no gap and no placeholder.
 * @returns {string}
 */
function renderRecentToolsSlot() {
    return '    <div class="recent-tools-slot" id="recent-tools-root"></div>';
}

/**
 * v4 hero: mono eyebrow stats, gradient display title, one-line value prop,
 * CTA pair, and the search island. The long-form intro paragraph stays below
 * the hero (SEO copy is unchanged).
 * @param {string} title
 * @param {number} toolCount
 * @param {Array<{ id: string, label: string }>} catalogGroups
 * @returns {string}
 */
function renderHero(title, toolCount, catalogGroups) {
    return `    <section class="hero" aria-label="Introduction">
      <p class="hero-eyebrow">// ${toolCount} tools · 100% client-side · 0 uploads</p>
      <h1 class="main-title">${escapeHtml(title)}</h1>
      <p class="hero-tagline">Fast, free utilities that run entirely in your browser — your data never leaves the tab.</p>
      <div class="hero-actions">
        <a class="cta-button" href="#tools">Browse tools${renderInlineIcon('arrow-right')}</a>
        <a class="cta-button cta-button--ghost" href="#what-are-online-developer-tools">Why client-side?</a>
      </div>
${renderToolSearchShell(catalogGroups)}
${renderRecentToolsSlot()}
    </section>`;
}

/**
 * @returns {string}
 */
function generateRootDocument() {
    const manifest = loadManifest();
    const groupedTools = getGroupedToolDefinitions();
    const structuredDataScript = renderStructuredDataScript(buildRootStructuredDataGraph(manifest));
    const analyticsHeadMarkup = renderAnalyticsHeadMarkup(manifest.analytics);
    const analyticsResourceHints = renderAnalyticsResourceHints(manifest.analytics);
    const escapedTitle = escapeAttribute(manifest.rootPage.title);
    const documentTitle = formatRootDocumentTitle(manifest.rootPage.title, manifest.organization.name);
    const escapedDescription = escapeAttribute(manifest.rootPage.description);
    const escapedCanonical = escapeAttribute(manifest.rootPage.absoluteUrl);
    const escapedSiteName = escapeAttribute(manifest.siteName);
    const escapedImageUrl = escapeAttribute(manifest.rootPage.imageUrl);
    const escapedImageAlt = escapeAttribute(`${manifest.siteName} — free online developer tools`);
    const escapedRootShellStylesUrl = escapeAttribute(buildAbsoluteUrl(manifest.siteStaticRootUri, '/root-shell/styles.main.css'));
    const escapedRootStylesUrl = escapeAttribute(buildAbsoluteUrl(manifest.siteStaticRootUri, '/styles.css'));
    const escapedRootShellBundleUrl = escapeAttribute(buildAbsoluteUrl(manifest.siteStaticRootUri, '/root-shell/bundle.main.js'));

    return `<!DOCTYPE html>
<html lang="en" data-theme="dark">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  ${THEME_INIT_SCRIPT}
  <title>${escapeHtml(documentTitle)}</title>
  <meta name="description" content="${escapedDescription}">
  <meta name="theme-color" content="${THEME_COLOR}">
  ${renderFaviconLinks(manifest.siteStaticRootUri)}
  ${renderFontPreloads(manifest.siteStaticRootUri)}${analyticsResourceHints ? `\n  ${analyticsResourceHints}` : ''}
  <link rel="canonical" href="${escapedCanonical}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${escapedSiteName}">
  <meta property="og:title" content="${escapedTitle}">
  <meta property="og:description" content="${escapedDescription}">
  <meta property="og:url" content="${escapedCanonical}">
  <meta property="og:image" content="${escapedImageUrl}">
  <meta property="og:image:alt" content="${escapedImageAlt}">
  <meta property="og:image:width" content="${OG_IMAGE_WIDTH}">
  <meta property="og:image:height" content="${OG_IMAGE_HEIGHT}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${escapedTitle}">
  <meta name="twitter:description" content="${escapedDescription}">
  <meta name="twitter:image" content="${escapedImageUrl}">
  <meta name="twitter:image:alt" content="${escapedImageAlt}">
  <link rel="image_src" href="${escapedImageUrl}">
  <link rel="stylesheet" href="${escapedRootShellStylesUrl}">
  <link rel="stylesheet" href="${escapedRootStylesUrl}">
  ${structuredDataScript}${analyticsHeadMarkup ? `\n  ${analyticsHeadMarkup}` : ''}
</head>
<body class="landing-page">
  <div id="app-shell-header"></div>

  <main class="main-container" aria-label="Tools index">
${renderHero(manifest.rootPage.title, groupedTools.reduce((count, group) => count + group.tools.length, 0), groupedTools)}

${renderRootPageIntro()}

    <div id="tools" class="tools-index">
${groupedTools.map((group) => {
        const slug = getGroupCategorySlug(group.id);
        return `    <section class="tool-group" data-tool-group="${escapeAttribute(group.id)}" aria-labelledby="${escapeAttribute(`group-${group.id}`)}">
      <h2 class="section-title section-title--${escapeAttribute(slug)}" id="${escapeAttribute(`group-${group.id}`)}">${escapeHtml(group.label)}</h2>
      <div class="tools-grid">
${group.tools.map((tool) => renderToolCard(tool, slug)).join('\n')}
      </div>
    </section>`;
    }).join('\n\n')}
    </div>

${renderRootPagePostIndexSections()}

  </main>

  <div id="app-shell-footer"></div>
  <script src="${escapedRootShellBundleUrl}" defer></script>
</body>
</html>
`;
}

module.exports = {
    generateRootDocument
};
