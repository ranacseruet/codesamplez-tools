// @ts-check

const { getToolById, loadManifest } = require('./tool-manifest');
const {
    renderRelatedToolsPrerenderMarkup,
    renderToolAfterAppPrerenderMarkup,
    renderToolBeforeAppPrerenderMarkup,
    renderToolPrerenderMarkup
} = require('./prerender-tool');
const { escapeAttribute, escapeHtml, formatToolDocumentTitle, joinUrl } = require('./document-helpers');
const { buildToolStructuredDataGraph, renderStructuredDataScript } = require('./structured-data');
const { renderAnalyticsHeadMarkup, renderAnalyticsResourceHints } = require('./analytics');
const { getToolFaqItems } = require('./tool-faq-metadata');
const { getToolHowToSteps } = require('./tool-howto-metadata');
const { getToolFeatureList } = require('./tool-feature-metadata');
const { getBuildCommitAttributeMarkup } = require('./provenance-manifest');
const { ensureBabelRegister } = require('./register-node-transforms');

const THEME_COLOR = '#0b0b11';

// Social card dimensions — matches the 1200x630 OG images generated by
// scripts/generate-og-images.mjs.
const OG_IMAGE_WIDTH = '1200';
const OG_IMAGE_HEIGHT = '630';

// Pre-paint theme init: apply the saved theme (default dark) before CSS paints
// so the choice persists across pages with no flash. Must run before stylesheets.
const THEME_INIT_SCRIPT = `<script>(function(){try{var t=localStorage.getItem('cst-standalone-theme-mode');var m=t==='light'?'light':'dark';var e=document.documentElement;e.setAttribute('data-theme',m);e.setAttribute('data-cst-theme',m);}catch(e){}})();</script>`;

// v2 design system: self-hosted Geist fonts (icons are inlined SVGs — no CDN).
// Preloads use the configured static-root absolute URL so they resolve to the
// same asset origin as the stylesheet (pages and assets can be cross-origin).
function renderFontPreloads(staticRootUri) {
    return ['Geist-Variable.woff2', 'GeistMono-Variable.woff2']
        .map((file) => `<link rel="preload" href="${escapeAttribute(joinUrl(staticRootUri, `/fonts/${file}`))}" as="font" type="font/woff2" crossorigin>`)
        .join('\n    ');
}

// Favicons resolve against the configured static-root absolute URL (same origin
// as the stylesheet/fonts) so they work from every tool path even when pages and
// assets are served cross-origin. SVG is the primary icon; ICO/PNG are fallbacks.
function renderFaviconLinks(staticRootUri) {
    return [
        `<link rel="icon" href="${escapeAttribute(joinUrl(staticRootUri, '/favicon.ico'))}" sizes="any">`,
        `<link rel="icon" type="image/svg+xml" href="${escapeAttribute(joinUrl(staticRootUri, '/favicon.svg'))}">`,
        `<link rel="apple-touch-icon" href="${escapeAttribute(joinUrl(staticRootUri, '/apple-touch-icon.png'))}">`
    ].join('\n    ');
}

/**
 * @typedef {import('./tool-manifest').ToolDefinition} ToolDefinition
 */

/**
 * @param {ToolDefinition} tool
 * @param {string} prerenderedMarkup
 * @param {string} relatedToolsMarkup
 * @param {string} beforeAppMarkup
 * @param {string} afterAppMarkup
 * @returns {string}
 */
function renderToolDocument(tool, prerenderedMarkup, relatedToolsMarkup = '', beforeAppMarkup = '', afterAppMarkup = '') {
    const manifest = loadManifest();
    const absolutePageUrl = joinUrl(tool.siteBaseUrl, tool.publicPath);
    const absoluteFeaturedImageUrl = joinUrl(tool.siteStaticRootUri, `${tool.publicPath.replace(/\/$/, '')}/${tool.featuredImagePath}`);
    const absoluteStylesUrl = joinUrl(tool.siteStaticRootUri, `${tool.publicPath.replace(/\/$/, '')}/styles.main.css`);
    const absoluteBundleUrl = joinUrl(tool.siteStaticRootUri, `${tool.publicPath.replace(/\/$/, '')}/bundle.main.js`);
    const escapedTitle = escapeAttribute(tool.title);
    const documentTitle = formatToolDocumentTitle(tool.seoTitle, manifest.organization.name);
    const escapedDescription = escapeAttribute(tool.description);
    const escapedAppRootId = escapeAttribute(tool.appRootId);
    const escapedMainHeadingId = escapeAttribute(`${tool.appRootId}-workspace-heading`);
    const workspaceHeading = `${tool.title} workspace`;
    const escapedSiteName = escapeAttribute(manifest.siteName);
    const escapedPageUrl = escapeAttribute(absolutePageUrl);
    const escapedStylesUrl = escapeAttribute(absoluteStylesUrl);
    const escapedBundleUrl = escapeAttribute(absoluteBundleUrl);
    const escapedFeaturedImageUrl = escapeAttribute(absoluteFeaturedImageUrl);
    const escapedFeaturedAlt = escapeAttribute(`${tool.title} featured image`);
    const structuredDataOptions = tool.structuredData;
    const structuredDataScript = renderStructuredDataScript(buildToolStructuredDataGraph(manifest, tool, {
        faqItems: structuredDataOptions.includeFaq ? getToolFaqItems(tool.id) : [],
        howToSteps: structuredDataOptions.includeHowTo ? getToolHowToSteps(tool.id) : [],
        featureList: getToolFeatureList(tool.id)
    }));
    const analyticsHeadMarkup = renderAnalyticsHeadMarkup(manifest.analytics);
    const analyticsResourceHints = renderAnalyticsResourceHints(manifest.analytics);
    const scriptTypeAttribute = tool.scriptType === 'module' ? ' type="module"' : '';
    const shellHeaderMarkup = renderToolShellHeaderMarkup(tool);
    const shellShareMarkup = renderToolShellShareMarkup(tool, absolutePageUrl);
    const shellFooterMarkup = renderToolShellFooterMarkup(tool);
    const wrappedBeforeMarkup = beforeAppMarkup
        ? `<div class="c-tool-static-shell c-tool-static-shell--before">${beforeAppMarkup}</div>`
        : '';
    // Related tools lead the after-app shell, ahead of the About intro and the
    // guide article. That position is the whole point: emitted last in the body
    // the section sat at 88% page depth, and only 14.2% of tool-page views ever
    // fire GA4's 90%-scroll event, so ~6 in 7 visitors never had the chance to
    // see it. Issue #327 moved every tool's article out of the app root, which
    // made this seam exist for all ten and let the runtime DOM move that used to
    // do this job go away (issue #497).
    const afterShellMarkup = `${relatedToolsMarkup}${afterAppMarkup}`;
    const wrappedAfterMarkup = afterShellMarkup
        ? `<div class="c-tool-static-shell c-tool-static-shell--after">${afterShellMarkup}</div>`
        : '';

    return `<!DOCTYPE html>
<html lang="en" data-theme="dark"${getBuildCommitAttributeMarkup()}>

<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    ${THEME_INIT_SCRIPT}
    <title>${escapeHtml(documentTitle)}</title>
    <meta name="description" content="${escapedDescription}">
    <meta name="tool-version" content="${escapeAttribute(tool.version)}">
    <meta name="theme-color" content="${THEME_COLOR}">
    ${renderFaviconLinks(tool.siteStaticRootUri)}
    ${renderFontPreloads(tool.siteStaticRootUri)}${analyticsResourceHints ? `\n    ${analyticsResourceHints}` : ''}
    <link rel="canonical" href="${escapedPageUrl}">
    <link rel="stylesheet" href="${escapedStylesUrl}">
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="${escapedSiteName}">
    <meta property="og:title" content="${escapedTitle}">
    <meta property="og:description" content="${escapedDescription}">
    <meta property="og:url" content="${escapedPageUrl}">
    <meta property="og:image" content="${escapedFeaturedImageUrl}">
    <meta property="og:image:alt" content="${escapedFeaturedAlt}">
    <meta property="og:image:width" content="${OG_IMAGE_WIDTH}">
    <meta property="og:image:height" content="${OG_IMAGE_HEIGHT}">
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="${escapedTitle}">
    <meta name="twitter:description" content="${escapedDescription}">
    <meta name="twitter:image" content="${escapedFeaturedImageUrl}">
    <meta name="twitter:image:alt" content="${escapedFeaturedAlt}">
    <link rel="image_src" href="${escapedFeaturedImageUrl}">
    ${structuredDataScript}${analyticsHeadMarkup ? `\n    ${analyticsHeadMarkup}` : ''}
</head>

<body class="standalone-app">
    <div id="app-shell-header">${shellHeaderMarkup}</div>
    <!-- c-tool-page-main is an unstyled semantic landmark hook. -->
    <main class="c-tool-page-main" aria-labelledby="${escapedMainHeadingId}">
        <h2 id="${escapedMainHeadingId}" class="u-visually-hidden">${escapeHtml(workspaceHeading)}</h2>
        ${wrappedBeforeMarkup}
        <div id="${escapedAppRootId}">${prerenderedMarkup}</div>
        ${wrappedAfterMarkup}
        <div id="app-shell-share">${shellShareMarkup}</div>
    </main>
    <div id="app-shell-footer">${shellFooterMarkup}</div>
    <script src="${escapedBundleUrl}"${scriptTypeAttribute}></script>
</body>

</html>
`;
}

/**
 * @param {ToolDefinition} tool
 * @returns {string}
 */
function renderToolShellHeaderMarkup(tool) {
    ensureBabelRegister();

    const { h } = require('preact');
    const renderToString = /** @type {(node: import('preact').VNode) => string} */ (
        /** @type {unknown} */ (require('preact-render-to-string'))
    );
    const { ToolShellHeader, createToolBreadcrumbItems } = require('../common/app-shell/AppShell');

    return renderToString(h(ToolShellHeader, {
        title: tool.title,
        description: tool.description,
        // Default home href (SITE_BASE_URL) so the server trail matches the client
        // re-render, which resolves homeHref '/' to the same shared base URL.
        breadcrumbItems: createToolBreadcrumbItems(tool.title)
    }));
}

/**
 * @param {ToolDefinition} tool
 * @param {string} shareUrl
 * @returns {string}
 */
function renderToolShellShareMarkup(tool, shareUrl) {
    ensureBabelRegister();

    const { h } = require('preact');
    const renderToString = /** @type {(node: import('preact').VNode) => string} */ (
        /** @type {unknown} */ (require('preact-render-to-string'))
    );
    const { ShareBar } = require('../common/app-shell/ShareBar');

    return renderToString(h(ShareBar, {
        shareUrl,
        shareTitle: tool.title
    }));
}

/**
 * @param {ToolDefinition} tool
 * @returns {string}
 */
function renderToolShellFooterMarkup(tool) {
    ensureBabelRegister();

    const { h } = require('preact');
    const renderToString = /** @type {(node: import('preact').VNode) => string} */ (
        /** @type {unknown} */ (require('preact-render-to-string'))
    );
    const { ToolShellFooter } = require('../common/app-shell/AppShell');

    return renderToString(h(ToolShellFooter, {
        homeHref: tool.siteBaseUrl
    }));
}

/**
 * @param {string} toolId
 * @returns {string}
 */
function generateToolDocument(toolId) {
    const tool = getToolById(toolId);
    if (!tool) {
        throw new Error(`Unknown tool id: ${toolId}`);
    }

    return renderToolDocument(
        tool,
        renderToolPrerenderMarkup(toolId),
        renderRelatedToolsPrerenderMarkup(toolId),
        renderToolBeforeAppPrerenderMarkup(toolId),
        renderToolAfterAppPrerenderMarkup(toolId)
    );
}

module.exports = {
    generateToolDocument,
    joinUrl,
    renderToolDocument,
    renderToolShellFooterMarkup,
    renderToolShellHeaderMarkup,
    renderToolShellShareMarkup
};
